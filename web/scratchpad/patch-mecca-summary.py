"""מכה: הפעולה היא שולחן הראיות, לא חידון שמות.

השאלה ששאלה „מי הן?" נענתה מילה במילה בשיחת הסוחר עצמה (merchant-goddesses,
רשומה 21) — כלומר התחנה ביקשה לחזור על מה שהוקרא. שלוש לוחיות השמות ירדו,
והפעולה היחידה במכה היא זו שהמשתמשת ביקשה: שלושת סוגי המקור על השולחן.
הסיכום עבר איתה — הוא מדבר על הפער בין העדויות, לא על שמות האלילות.

ובתחנת הגבול: הסיכום חזר על תשובת הפירוש („הדרך פונה אל הסאסאנית")
במקום להוסיף עליה.
"""
import io
p = 'src/lib/chapter1/tasks.ts'
s = io.open(p, encoding='utf-8').read()

# --- מכה: להסיר את חידון השמות ולהשאיר את השולחן ---
i = s.index("id: 'task-stones'")
j = s.index("    interpret: {", i)
blk = s[i:j]
new_blk = """id: 'task-stones',
    region: 'mecca',
    /* גילוי לפני שיפוט: שלושת חפצי הפולחן — האבן הניצבת, המטבע בכיכר
       ואשפת החיצים — נראים קודם ב-E, ורק אז שופטים.

       חידון השמות שהיה כאן („שלוש אבנים, ולכל אחת שם. מי הן?") ירד:
       הסוחר מוסר את שלושת השמות במפורש בשיחתו, ולכן התחנה ביקשה לחזור
       על מה שזה עתה הוקרא. הפעולה במכה היא שולחן הראיות — שלושת סוגי
       המקור, כל אחד במקומו — והשאלה שאחריה היא ההבחנה ביניהם. */
    needsFinds: ['find-ansab', 'find-mecca-coin', 'find-divination'],
    x: -1.8, z: -12.6, model: 'ansab', h: 1.6, ry: 0.2,
    prompt: 'סדרו את שולחן הראיות',
    title: 'שלושה מקורות, שלושה זמנים',
    asker: 'הסוחר',
    hint: 'הניחו כל מקור במקומו על השולחן: מה שנחצב באבן, מה שנאמר בפסוק, ומה שנכתב מאוחר יותר',
    question:
      'שלושה דברים מספרים כאן על אותו עניין, ולא באותו קול. הנח כל אחד במקומו, ' +
      'ואז נשווה ביניהם.',
    options: [],
"""
s = s[:i] + new_blk + s[j:]

s = s.replace(
    """    done:
      'רשמתי: אללאת, אלעזה ומנאת — ונחשבו לבנותיו של אללה.',""",
    """    done:
      'רשמתי את ההבדל: האבן נחרתה במקומה ובזמנה, והשאר מספרים עליו מרחוק — ' +
      'זה פסוק, וזה דף שנכתב דורות אחר כך. שלושתם מקורות; אין להם אותו קול.',""", 1)

# --- הגבול: הסיכום יוסיף במקום לחזור ---
s = s.replace(
    """    done: 'המאזניים הכריעו: מצפון לחצי האי שתי אימפריות, והדרך הזאת פונה אל הסאסאנית.',""",
    """    done:
      'רשמתי. ושים לב מה אין כאן: אף אחת מהשתיים אינה שולטת בדרך הזאת. ' +
      'הן קונות בקצה שלה, והשבט שומר עליה באמצע.',""", 1)

# --- ית'רב: לא הייתה הוראת פעולה כלל ---
s = s.replace(
    """    prompt: 'חברו בין החצרות',""",
    """    prompt: 'חברו בין החצרות',
    hint: 'תלו על החבל את מה שעבר בין הקהילות, והניחו בתוך החצרות את מה שכל אחת שמרה לעצמה',""", 1)

io.open(p, 'w', encoding='utf-8').write(s)
print('tasks.ts patched')
